// Adoption codemod (RFC-0002 Phase 7): swap supported RN primitives for
// Mapples primitives, assign fresh `c_` sids, wrap unsupported components as
// Custom (import ref recorded, $fallback attached). Span-based edits — user
// code outside the touched tags is preserved byte-for-byte.
//
// A swapped primitive also gets its props translated to the @mapples/ui
// contract, because a bare rename would leave the canvas with an unstyled
// node: React Native's `style` is an expression (`styles.card`) the extractor
// cannot serialize, and even a literal one lands in `props.style` while the
// Creator (and every Mapples component) reads `styled.style`. So `style`,
// `contentContainerStyle` and `placeholderTextColor` become entries of a
// `styled` literal, resolved through the file's `StyleSheet.create` (or plain
// object) dictionaries and merged across style arrays; an Image's
// `{ uri }` source becomes the string the Creator stores and `resizeMode`
// becomes expo-image's `contentFit`; a Pressable whose only child is a
// literal Text becomes a Button with `label` + `styleTypography` (the Creator
// does not render Button children). A style dictionary every reference of
// which was inlined is removed together with its `StyleSheet` import.
// Anything the codemod cannot resolve stays as the user wrote it, inside the
// `styled` literal, and extraction reports it as NON_LITERAL_PROP.

import ts from 'typescript';

import { evalLiteral } from './parse.js';
import { collectStyleDicts as collectSharedStyleDicts } from './styleDicts.js';
import type { Span } from './types.js';

export interface ScanInfo {
  hasSid: boolean;
  hasJsx: boolean;
  exportedComponents: string[]; // PascalCase exported function/const components
  markers: string[]; // mapples-route / generated markers found in the header
}

export function scanComponents(source: string): ScanInfo {
  const sf = ts.createSourceFile(
    'f.tsx',
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );
  const exported: string[] = [];
  const isComponentName = (name: string): boolean => /^[A-Z]/.test(name);

  for (const stmt of sf.statements) {
    const isExport = ts.canHaveModifiers(stmt)
      ? (ts
          .getModifiers(stmt)
          ?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) ?? false)
      : false;
    if (
      ts.isFunctionDeclaration(stmt) &&
      stmt.name &&
      isExport &&
      isComponentName(stmt.name.text)
    ) {
      exported.push(stmt.name.text);
    }
    if (ts.isVariableStatement(stmt) && isExport) {
      for (const decl of stmt.declarationList.declarations) {
        if (ts.isIdentifier(decl.name) && isComponentName(decl.name.text)) {
          exported.push(decl.name.text);
        }
      }
    }
    if (ts.isExportAssignment(stmt) && !stmt.isExportEquals) {
      exported.push('default');
    }
  }
  const markers: string[] = [];
  const headMatch =
    /\/\/\s*(mapples-route:[^\n]*|GENERATED by Mapples[^\n]*)/.exec(source);
  if (headMatch) markers.push(headMatch[1]!);
  return {
    hasSid: /\$sid\s*=/.test(source),
    hasJsx: containsJsx(sf),
    exportedComponents: exported,
    markers,
  };
}

function containsJsx(node: ts.Node): boolean {
  let found = false;
  const walk = (n: ts.Node): void => {
    if (found) return;
    if (ts.isJsxElement(n) || ts.isJsxSelfClosingElement(n)) {
      found = true;
      return;
    }
    ts.forEachChild(n, walk);
  };
  walk(node);
  return found;
}

export interface CodemodOptions {
  /** RN element name -> Mapples primitive type (e.g. Pressable -> Button). */
  mapping: Record<string, string>;
  /** Mint a fresh c_ sid for each adopted element. */
  mintSid: () => string;
  /** Module whose imports count as the RN source (default 'react-native'). */
  rnModule?: string;
  /** Module the swapped primitives are imported from (default '@mapples/ui'). */
  uiModule?: string;
  /**
   * An import the caller links to a Creator component (a managed component
   * file): the element is tagged and its props translated like a primitive,
   * with no `$fallback` — the canvas renders the component itself.
   */
  isLinked?: (origin: { module: string; exportName: string }) => boolean;
}

export interface AdoptedElement {
  sid: string;
  originalName: string;
  kind: 'primitive' | 'custom';
  mappedName?: string; // primitives only
  importRef?: string; // customs only
  fallbackSize?: { w: number; h: number };
}

export interface CodemodResult {
  source: string;
  adopted: AdoptedElement[];
  skipped: { name: string; reason: string }[];
}

interface Edit {
  start: number;
  end: number;
  replacement: string;
}

/** RN `resizeMode` -> expo-image `contentFit` (the prop the Creator's Image edits). */
const CONTENT_FIT: Record<string, string> = {
  cover: 'cover',
  contain: 'contain',
  stretch: 'fill',
  center: 'none',
};

const PRINT_WIDTH = 100;

type Literal = Record<string, unknown>;

/**
 * A `styled` entry after resolution: a literal object, a plain string (colors),
 * or the expression as the user wrote it.
 */
type ResolvedStyle =
  | { literal: Literal }
  | { str: string }
  | { expr: string }
  /** A `styles.card` reference kept as written, with the literal it names. */
  | { ref: string; dict: string; literal: Literal };

interface StyleDict {
  name: string;
  statement: ts.VariableStatement;
  /** `StyleSheet.create` identifier the dictionary was built with, when it was. */
  sheetIdent: ts.Identifier | null;
  entries: Map<string, ts.ObjectLiteralExpression>;
}

export function codemodAdopt(
  source: string,
  options: CodemodOptions,
): CodemodResult {
  const rnModule = options.rnModule ?? 'react-native';
  const uiModule = options.uiModule ?? '@mapples/ui';
  const sf = ts.createSourceFile(
    'f.tsx',
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );

  // ---- imports ----
  const importOrigin = new Map<
    string,
    { module: string; exportName: string }
  >();
  let rnImportDecl: ts.ImportDeclaration | null = null;
  let uiImportDecl: ts.ImportDeclaration | null = null;
  let lastImportEnd = 0;
  for (const stmt of sf.statements) {
    if (
      !ts.isImportDeclaration(stmt) ||
      !ts.isStringLiteral(stmt.moduleSpecifier)
    )
      continue;
    lastImportEnd = stmt.getEnd();
    const module = stmt.moduleSpecifier.text;
    if (module === rnModule) rnImportDecl = stmt;
    if (module === uiModule) uiImportDecl = stmt;
    const clause = stmt.importClause;
    if (!clause) continue;
    if (clause.name)
      importOrigin.set(clause.name.text, { module, exportName: 'default' });
    if (clause.namedBindings && ts.isNamedImports(clause.namedBindings)) {
      for (const el of clause.namedBindings.elements) {
        importOrigin.set(el.name.text, {
          module,
          exportName: (el.propertyName ?? el.name).text,
        });
      }
    }
  }

  // ---- style dictionaries (`const styles = StyleSheet.create({…})` / `= {…}`) ----
  const styleDicts = collectStyleDicts(sf, importOrigin, rnModule);
  const dictRefsInlined = new Map<string, number>();

  const edits: Edit[] = [];
  const adopted: AdoptedElement[] = [];
  const skipped: { name: string; reason: string }[] = [];
  const usedUiNames = new Set<string>();
  const swappedRnNames = new Set<string>();
  const renamedTagStarts = new Set<number>();

  const unwrap = (expr: ts.Expression): ts.Expression =>
    ts.isParenthesizedExpression(expr) ? unwrap(expr.expression) : expr;

  /** Resolve a style expression to a literal object where the file makes that possible. */
  const resolveStyle = (expr: ts.Expression): ResolvedStyle => {
    const e = unwrap(expr);
    if (ts.isObjectLiteralExpression(e)) {
      const v = evalLiteral(e);
      return isRecord(v) ? { literal: v } : { expr: e.getText(sf) };
    }
    if (ts.isPropertyAccessExpression(e) && ts.isIdentifier(e.expression)) {
      const dict = styleDicts.get(e.expression.text);
      const entry = dict?.entries.get(e.name.text);
      if (dict && entry) {
        const v = evalLiteral(entry);
        if (isRecord(v)) {
          if (Object.keys(v).length === 0) {
            // An empty entry says nothing: inline (to nothing) and let the
            // dictionary go when that was its last reference.
            dictRefsInlined.set(
              dict.name,
              (dictRefsInlined.get(dict.name) ?? 0) + 1,
            );
            return { literal: v };
          }
          // The developer keeps styles in a dictionary: so does the file.
          // Extraction reads the reference as the entry it names.
          return { ref: e.getText(sf), dict: dict.name, literal: v };
        }
      }
      return { expr: e.getText(sf) };
    }
    if (ts.isArrayLiteralExpression(e)) {
      // Style arrays merge left to right — the same result RN computes at
      // runtime, as one object the Creator can edit. The references inside
      // are inlined: one `style` cannot name two entries.
      const merged: Literal = {};
      const before = new Map(dictRefsInlined);
      for (const el of e.elements) {
        const r = resolveStyle(el);
        if (!('literal' in r)) {
          dictRefsInlined.clear();
          for (const [k, v] of before) dictRefsInlined.set(k, v);
          return { expr: e.getText(sf) };
        }
        if ('ref' in r)
          dictRefsInlined.set(r.dict, (dictRefsInlined.get(r.dict) ?? 0) + 1);
        Object.assign(merged, r.literal);
      }
      return { literal: merged };
    }
    return { expr: e.getText(sf) };
  };

  const measureFallback = (
    attributes: ts.JsxAttributes,
  ): { w: number; h: number } => {
    // Measured from a literal style {width, height} when present, else defaulted.
    for (const prop of attributes.properties) {
      if (
        !ts.isJsxAttribute(prop) ||
        !ts.isIdentifier(prop.name) ||
        prop.name.text !== 'style'
      )
        continue;
      if (
        prop.initializer &&
        ts.isJsxExpression(prop.initializer) &&
        prop.initializer.expression
      ) {
        const expr = unwrap(prop.initializer.expression);
        if (ts.isObjectLiteralExpression(expr)) {
          let w = 100;
          let h = 100;
          for (const p of expr.properties) {
            if (
              ts.isPropertyAssignment(p) &&
              ts.isIdentifier(p.name) &&
              ts.isNumericLiteral(p.initializer)
            ) {
              if (p.name.text === 'width') w = Number(p.initializer.text);
              if (p.name.text === 'height') h = Number(p.initializer.text);
            }
          }
          return { w, h };
        }
      }
    }
    return { w: 100, h: 100 };
  };

  const findAttr = (
    attributes: ts.JsxAttributes,
    attr: string,
  ): ts.JsxAttribute | null => {
    for (const p of attributes.properties) {
      if (
        ts.isJsxAttribute(p) &&
        ts.isIdentifier(p.name) &&
        p.name.text === attr
      )
        return p;
    }
    return null;
  };
  const hasAttr = (attributes: ts.JsxAttributes, attr: string): boolean =>
    findAttr(attributes, attr) !== null;
  const hasSidAttr = (attributes: ts.JsxAttributes): boolean =>
    hasAttr(attributes, '$sid');

  const attrExpression = (attr: ts.JsxAttribute): ts.Expression | null =>
    attr.initializer &&
    ts.isJsxExpression(attr.initializer) &&
    attr.initializer.expression
      ? attr.initializer.expression
      : null;
  const attrString = (attr: ts.JsxAttribute): string | null => {
    if (!attr.initializer) return null;
    if (ts.isStringLiteral(attr.initializer)) return attr.initializer.text;
    const e = attrExpression(attr);
    if (e) {
      const u = unwrap(e);
      if (ts.isStringLiteral(u) || ts.isNoSubstitutionTemplateLiteral(u))
        return u.text;
    }
    return null;
  };

  /** Remove an attribute together with the whitespace that led to it. */
  const removeAttr = (attr: ts.JsxAttribute): void => {
    let start = attr.getStart(sf);
    while (start > 0 && /\s/.test(source[start - 1]!)) start -= 1;
    edits.push({ start, end: attr.getEnd(), replacement: '' });
  };

  /**
   * The one literal string child of an element, whitespace-normalized; null
   * when the children are anything else (expressions, elements, mixed runs).
   */
  const literalTextChild = (element: ts.JsxElement): string | null => {
    let text: string | null = null;
    for (const child of element.children) {
      if (ts.isJsxText(child)) {
        const normalized = child.text.replace(/\s+/g, ' ').trim();
        if (normalized === '') continue;
        if (text !== null) return null;
        text = normalized;
        continue;
      }
      return null;
    }
    return text;
  };

  /** The only element child (whitespace ignored), or null. */
  const soleElementChild = (element: ts.JsxElement): ts.JsxElement | null => {
    let found: ts.JsxElement | null = null;
    for (const child of element.children) {
      if (ts.isJsxText(child) && child.text.trim() === '') continue;
      if (ts.isJsxElement(child) && found === null) {
        found = child;
        continue;
      }
      return null;
    }
    return found;
  };

  /** The Mapples type a react-native import maps to — by export name, so `Text as RNText` counts. */
  const mappedType = (name: string): string | null => {
    const origin = importOrigin.get(name);
    if (origin?.module !== rnModule) return null;
    return options.mapping[origin.exportName] ?? null;
  };

  const isTextTag = (name: string): boolean => {
    const origin = importOrigin.get(name);
    if (!origin) return false;
    if (origin.module === rnModule) return mappedType(name) === 'Text';
    return origin.module === uiModule && origin.exportName === 'Text';
  };

  /**
   * Prop translation for a swapped primitive. Returns the attribute text to
   * add after `$sid` (label / text / source / contentFit / styled) and whether
   * the element's children were folded away.
   */
  const translateProps = (
    node: ts.JsxElement | ts.JsxSelfClosingElement,
    open: ts.JsxOpeningElement | ts.JsxSelfClosingElement,
    mapped: string,
  ): { attrText: string; foldChildren: boolean } => {
    const attrs = open.attributes;
    const styled: { key: string; value: ResolvedStyle }[] = [];
    let attrText = '';
    let foldChildren = false;

    // Text copy: `<Text>Hi</Text>` -> `text="Hi"` (the Creator never renders
    // `props.children`).
    if (mapped === 'Text' && ts.isJsxElement(node) && !hasAttr(attrs, 'text')) {
      const text = literalTextChild(node);
      if (text !== null) {
        attrText += ` text=${printJsxString(text)}`;
        foldChildren = true;
      }
    }

    // Button copy: `<Pressable><Text style={s}>Save</Text></Pressable>` ->
    // `label="Save"` + `styleTypography` — Button children do not render.
    if (
      mapped === 'Button' &&
      ts.isJsxElement(node) &&
      !hasAttr(attrs, 'label')
    ) {
      const child = soleElementChild(node);
      const childOpen = child?.openingElement;
      if (
        child &&
        childOpen &&
        ts.isIdentifier(childOpen.tagName) &&
        isTextTag(childOpen.tagName.text) &&
        !hasSidAttr(childOpen.attributes) &&
        childOpen.attributes.properties.every(
          (p) =>
            ts.isJsxAttribute(p) &&
            ts.isIdentifier(p.name) &&
            p.name.text === 'style',
        )
      ) {
        const text = literalTextChild(child);
        if (text !== null) {
          attrText += ` label=${printJsxString(text)}`;
          const style = findAttr(childOpen.attributes, 'style');
          const expr = style ? attrExpression(style) : null;
          if (expr)
            styled.push({ key: 'styleTypography', value: resolveStyle(expr) });
          foldChildren = true;
        }
      }
      if (
        !foldChildren &&
        node.children.some((c) => !(ts.isJsxText(c) && c.text.trim() === ''))
      ) {
        skipped.push({
          name: open.tagName.getText(sf),
          reason: `${open.tagName.getText(sf)} children other than one literal Text are not rendered by the Creator's Button — kept in code only`,
        });
      }
    }

    if (hasAttr(attrs, 'styled')) return { attrText, foldChildren };

    // `style` -> styled.style (resolved through StyleSheet dictionaries).
    const style = findAttr(attrs, 'style');
    const styleExpr = style ? attrExpression(style) : null;
    if (style && styleExpr) {
      const resolved = resolveStyle(styleExpr);
      styled.unshift({ key: 'style', value: resolved });
      removeAttr(style);
      if (mapped === 'Image') {
        // RN sizes the image itself; the Mapples Image sizes a container and
        // lets the picture fill it (rounded corners clip on both).
        const fill: Literal = { width: '100%', height: '100%' };
        if ('literal' in resolved) {
          for (const [k, v] of Object.entries(resolved.literal)) {
            if (k.startsWith('border') && k.includes('Radius')) fill[k] = v;
          }
        }
        styled.push({ key: 'styleImage', value: { literal: fill } });
      }
    }

    if (mapped === 'ScrollView' || mapped === 'FlatList') {
      const ccs = findAttr(attrs, 'contentContainerStyle');
      const expr = ccs ? attrExpression(ccs) : null;
      if (ccs && expr) {
        styled.push({
          key: 'contentContainerStyle',
          value: resolveStyle(expr),
        });
        removeAttr(ccs);
      }
    }

    if (mapped === 'TextInput') {
      const color = findAttr(attrs, 'placeholderTextColor');
      if (color) {
        const s = attrString(color);
        const expr = attrExpression(color);
        const value: ResolvedStyle | null =
          s !== null ? { str: s } : expr ? { expr: expr.getText(sf) } : null;
        if (value) {
          styled.push({ key: 'placeholderTextColor', value });
          removeAttr(color);
        }
      }
    }

    if (mapped === 'Image') {
      const src = findAttr(attrs, 'source');
      const expr = src ? attrExpression(src) : null;
      if (src && expr) {
        const u = unwrap(expr);
        if (ts.isObjectLiteralExpression(u)) {
          const v = evalLiteral(u);
          if (
            isRecord(v) &&
            typeof v.uri === 'string' &&
            Object.keys(v).length === 1
          ) {
            attrText += ` source=${printJsxString(v.uri)}`;
            removeAttr(src);
          }
        }
      }
      const mode = findAttr(attrs, 'resizeMode');
      const modeValue = mode ? attrString(mode) : null;
      if (
        mode &&
        modeValue !== null &&
        CONTENT_FIT[modeValue] &&
        !hasAttr(attrs, 'contentFit')
      ) {
        attrText += ` contentFit="${CONTENT_FIT[modeValue]}"`;
        removeAttr(mode);
      }
    }

    // An empty style says nothing worth keeping in the file.
    const kept = styled.filter(
      (e) =>
        !('literal' in e.value && Object.keys(e.value.literal).length === 0),
    );
    if (kept.length > 0) {
      const indent = lineIndent(source, open.getStart(sf));
      attrText += ` styled=${printStyled(kept, indent)}`;
    }
    return { attrText, foldChildren };
  };

  const visit = (node: ts.Node): void => {
    let open: ts.JsxOpeningElement | ts.JsxSelfClosingElement | null = null;
    let close: ts.JsxClosingElement | null = null;
    if (ts.isJsxElement(node)) {
      open = node.openingElement;
      close = node.closingElement;
    } else if (ts.isJsxSelfClosingElement(node)) {
      open = node;
    }

    let skipChildren = false;
    if (open && ts.isIdentifier(open.tagName) && !hasSidAttr(open.attributes)) {
      const name = open.tagName.text;
      if (/^[A-Z]/.test(name)) {
        const origin = importOrigin.get(name);
        const sid = options.mintSid();
        const nameSpan: Span = {
          start: open.tagName.getStart(sf),
          end: open.tagName.getEnd(),
        };
        const element = node as ts.JsxElement | ts.JsxSelfClosingElement;

        // `<Tag …>…children…</Tag>` -> `<Tag … />`
        const foldChildren = (): void => {
          if (!ts.isJsxElement(node)) return;
          edits.push({
            start: node.openingElement.getEnd() - 1,
            end: node.getEnd(),
            replacement: ' />',
          });
          skipChildren = true;
        };

        const mappedRn = mappedType(name);
        if (origin?.module === rnModule && mappedRn) {
          const mapped = mappedRn;
          const translated = translateProps(element, open, mapped);
          edits.push({
            start: nameSpan.start,
            end: nameSpan.end,
            replacement: mapped,
          });
          renamedTagStarts.add(nameSpan.start);
          if (close && ts.isIdentifier(close.tagName)) {
            // A folded element loses its closing tag altogether; either way
            // that identifier no longer references the react-native import.
            if (!translated.foldChildren) {
              edits.push({
                start: close.tagName.getStart(sf),
                end: close.tagName.getEnd(),
                replacement: mapped,
              });
            }
            renamedTagStarts.add(close.tagName.getStart(sf));
          }
          edits.push({
            start: nameSpan.end,
            end: nameSpan.end,
            replacement: ` $sid="${sid}"${translated.attrText}`,
          });
          if (translated.foldChildren) foldChildren();
          usedUiNames.add(mapped);
          swappedRnNames.add(name);
          adopted.push({
            sid,
            originalName: name,
            kind: 'primitive',
            mappedName: mapped,
          });
        } else if (origin?.module === uiModule) {
          // Already a Mapples primitive in code: tag it, and translate the
          // react-native-style props a developer writes from habit
          // (`style={…}`, a Text child) — a `styled` it already has is kept.
          const translated = translateProps(element, open, origin.exportName);
          edits.push({
            start: nameSpan.end,
            end: nameSpan.end,
            replacement: ` $sid="${sid}"${translated.attrText}`,
          });
          if (translated.foldChildren) {
            if (close && ts.isIdentifier(close.tagName)) {
              renamedTagStarts.add(close.tagName.getStart(sf));
            }
            foldChildren();
          }
          adopted.push({
            sid,
            originalName: name,
            kind: 'primitive',
            mappedName: name,
          });
        } else if (origin?.module === rnModule) {
          skipped.push({
            name,
            reason: `react-native ${name} has no Mapples mapping — left as-is`,
          });
        } else if (origin && options.isLinked?.(origin)) {
          // A Creator component used from code: a linked instance, not an
          // opaque Custom — `style` becomes the instance's `styled`.
          const translated = translateProps(element, open, 'ComponentInstance');
          edits.push({
            start: nameSpan.end,
            end: nameSpan.end,
            replacement: ` $sid="${sid}"${translated.attrText}`,
          });
          adopted.push({
            sid,
            originalName: name,
            kind: 'primitive',
            mappedName: 'ComponentInstance',
          });
        } else {
          // Unsupported component -> opaque Custom node.
          const fallbackSize = measureFallback(open.attributes);
          const importRef = origin
            ? `${origin.module}#${origin.exportName}`
            : `#${name}`;
          edits.push({
            start: nameSpan.end,
            end: nameSpan.end,
            replacement: ` $sid="${sid}" $fallback={{ h: ${fallbackSize.h}, w: ${fallbackSize.w} }}`,
          });
          adopted.push({
            sid,
            originalName: name,
            kind: 'custom',
            importRef,
            fallbackSize,
          });
        }
      }
    }
    // Recurse the way extraction reads: into an element's CHILDREN, never its
    // attributes. JSX inside a render prop (`renderItem={() => <Card />}`) is
    // invisible to the canvas, so tagging it minted a `c_` sid that no push
    // would ever resolve.
    if (ts.isJsxElement(node)) {
      if (!skipChildren) for (const child of node.children) visit(child);
      return;
    }
    if (ts.isJsxSelfClosingElement(node)) return;
    ts.forEachChild(node, visit);
  };
  visit(sf);

  if (adopted.length === 0) {
    return { source, adopted, skipped };
  }

  // ---- dead style dictionaries ----
  // A dictionary whose every reference was inlined has nothing left to say;
  // its statement goes, and so does `StyleSheet` when that was its last use.
  const removedStatements: ts.Node[] = [];
  const removedSheetIdents = new Set<string>();
  for (const [name, count] of dictRefsInlined) {
    const dict = styleDicts.get(name)!;
    const refs = countIdentifierRefs(sf, name, [dict.statement]);
    if (refs !== count) continue;
    let end = dict.statement.getEnd();
    if (source[end] === '\n') end += 1;
    let start = dict.statement.getStart(sf);
    // Take the blank line that separated it from the code above.
    if (source.slice(start - 2, start) === '\n\n') start -= 1;
    edits.push({ start, end, replacement: '' });
    removedStatements.push(dict.statement);
    if (dict.sheetIdent) removedSheetIdents.add(dict.sheetIdent.text);
  }

  // ---- import rewrites ----
  // Remove swapped names from the react-native import when they are no longer
  // referenced (identity swaps always shadow; renamed swaps checked by usage).
  if (
    rnImportDecl?.importClause?.namedBindings &&
    ts.isNamedImports(rnImportDecl.importClause.namedBindings)
  ) {
    const keep: string[] = [];
    for (const el of rnImportDecl.importClause.namedBindings.elements) {
      const name = el.name.text;
      if (removedSheetIdents.has(name)) {
        if (
          countIdentifierRefs(sf, name, [rnImportDecl, ...removedStatements]) >
          0
        ) {
          keep.push(el.getText(sf));
        }
        continue;
      }
      if (!swappedRnNames.has(name)) {
        keep.push(el.getText(sf));
        continue;
      }
      const mapped = options.mapping[(el.propertyName ?? el.name).text];
      if (
        mapped !== name &&
        stillReferenced(sf, el.name, rnImportDecl, renamedTagStarts)
      ) {
        keep.push(el.getText(sf));
      }
    }
    const bindings = rnImportDecl.importClause.namedBindings;
    if (keep.length === 0 && !rnImportDecl.importClause.name) {
      // whole import gone (plus its line break)
      let end = rnImportDecl.getEnd();
      if (source[end] === '\n') end += 1;
      edits.push({ start: rnImportDecl.getStart(sf), end, replacement: '' });
    } else {
      edits.push({
        start: bindings.getStart(sf),
        end: bindings.getEnd(),
        replacement: `{ ${keep.join(', ')} }`,
      });
    }
  }
  if (usedUiNames.size > 0) {
    const uiBindings = uiImportDecl?.importClause?.namedBindings;
    if (uiBindings && ts.isNamedImports(uiBindings)) {
      // The file already imports from @mapples/ui (a managed page gaining new
      // elements): grow that import instead of adding a second one.
      const names = new Set(uiBindings.elements.map((el) => el.getText(sf)));
      for (const name of usedUiNames) names.add(name);
      edits.push({
        start: uiBindings.getStart(sf),
        end: uiBindings.getEnd(),
        replacement: `{ ${[...names].sort().join(', ')} }`,
      });
    } else {
      const names = [...usedUiNames].sort().join(', ');
      edits.push({
        start: lastImportEnd,
        end: lastImportEnd,
        replacement: `\nimport { ${names} } from '${uiModule}';`,
      });
    }
  }

  // Later spans first so earlier offsets stay valid; at the same offset the
  // replacement goes before the insertion, or the insertion's text gets cut.
  edits.sort((a, b) => b.start - a.start || b.end - a.end);
  let out = source;
  for (const e of edits)
    out = out.slice(0, e.start) + e.replacement + out.slice(e.end);
  return { source: out, adopted, skipped };
}

function isRecord(v: unknown): v is Literal {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

/**
 * Top-level `const styles = StyleSheet.create({ a: {…} })`, `Styler.create({…})`
 * and `const styles = { a: {…} }` declarations, keyed by identifier — what
 * `style={styles.a}` refers to. `sheetIdent` names react-native's
 * `StyleSheet` when the dictionary was built with it, so the import can go
 * with the last reference.
 */
function collectStyleDicts(
  sf: ts.SourceFile,
  importOrigin: Map<string, { module: string; exportName: string }>,
  rnModule: string,
): Map<string, StyleDict> {
  const dicts = new Map<string, StyleDict>();
  for (const [name, dict] of collectSharedStyleDicts(sf)) {
    const origin = dict.creator
      ? importOrigin.get(dict.creator.text)
      : undefined;
    const sheetIdent =
      dict.creator &&
      origin?.module === rnModule &&
      origin.exportName === 'StyleSheet'
        ? dict.creator
        : null;
    const entries = new Map<string, ts.ObjectLiteralExpression>();
    for (const [key, entry] of dict.entries) entries.set(key, entry.node);
    dicts.set(name, { name, statement: dict.statement, sheetIdent, entries });
  }
  return dicts;
}

/** Identifier references to `name` outside the given nodes (declarations excluded). */
function countIdentifierRefs(
  sf: ts.SourceFile,
  name: string,
  exclude: ts.Node[],
): number {
  let count = 0;
  const walk = (n: ts.Node): void => {
    if (exclude.includes(n)) return;
    if (ts.isIdentifier(n) && n.text === name) {
      const parent = n.parent;
      // `obj.name` — the name side of a property access is not a reference.
      if (!(ts.isPropertyAccessExpression(parent) && parent.name === n)) {
        if (!(ts.isPropertyAssignment(parent) && parent.name === n)) count += 1;
      }
    }
    ts.forEachChild(n, walk);
  };
  walk(sf);
  return count;
}

function stillReferenced(
  sf: ts.SourceFile,
  ident: ts.Identifier,
  withinImport: ts.Node,
  renamedTagStarts: Set<number>,
): boolean {
  let count = 0;
  const walk = (n: ts.Node): void => {
    if (
      n.getStart(sf) >= withinImport.getStart(sf) &&
      n.getEnd() <= withinImport.getEnd()
    ) {
      // skip the import declaration itself
      if (n !== withinImport) return;
    }
    if (
      ts.isIdentifier(n) &&
      n.text === ident.text &&
      n !== ident &&
      !renamedTagStarts.has(n.getStart(sf))
    ) {
      count += 1;
    }
    ts.forEachChild(n, walk);
  };
  walk(sf);
  return count > 0;
}

// ---- printing ----

/** Indentation of the line `pos` sits on. */
function lineIndent(source: string, pos: number): string {
  const lineStart = source.lastIndexOf('\n', pos - 1) + 1;
  const m = /^[ \t]*/.exec(source.slice(lineStart, pos));
  return m ? m[0] : '';
}

/** A JSX string attribute value: `"…"`, or `{'…'}` when the text has quotes. */
function printJsxString(text: string): string {
  return /["\\]/.test(text) ? `{${printString(text)}}` : `"${text}"`;
}

function printString(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function printKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : printString(key);
}

/** One-line JS literal. */
function printInline(v: unknown): string {
  if (typeof v === 'string') return printString(v);
  if (Array.isArray(v)) return `[${v.map(printInline).join(', ')}]`;
  if (isRecord(v)) {
    const entries = Object.entries(v);
    if (entries.length === 0) return '{}';
    return `{ ${entries.map(([k, x]) => `${printKey(k)}: ${printInline(x)}`).join(', ')} }`;
  }
  return String(v);
}

/** JS literal that fits `PRINT_WIDTH` on one line, else one property per line. */
function printValue(v: unknown, indent: string): string {
  const inline = printInline(v);
  if (indent.length + inline.length <= PRINT_WIDTH || !isRecord(v))
    return inline;
  const inner = indent + '  ';
  const lines = Object.entries(v).map(
    ([k, x]) => `${inner}${printKey(k)}: ${printValue(x, inner)},`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

/**
 * `{{ style: {…}, styleTypography: {…} }}` — literal entries printed, expression
 * entries verbatim. `placeholderTextColor` carries a string, not an object.
 */
function printStyled(
  entries: { key: string; value: ResolvedStyle }[],
  indent: string,
): string {
  const text = (value: ResolvedStyle, at: string): string => {
    if ('ref' in value) return value.ref;
    if ('expr' in value) return value.expr;
    if ('str' in value) return printString(value.str);
    return printValue(value.literal, at);
  };
  const inline = `{{ ${entries.map((e) => `${e.key}: ${text(e.value, indent)}`).join(', ')} }}`;
  if (indent.length + inline.length <= PRINT_WIDTH) return inline;
  const inner = indent + '  ';
  const lines = entries.map(
    (e) => `${inner}${e.key}: ${text(e.value, inner)},`,
  );
  return `{{\n${lines.join('\n')}\n${indent}}}`;
}
